/*
Purpose: Create deterministic STG -> NDS cleaning views for Home Credit.
Dependency: stg tables and etl schema.
Safety: Views only; raw and staging values are never changed.
*/

SET NOCOUNT ON;
GO

CREATE OR ALTER VIEW etl.vw_CleanApplicant
AS
SELECT
    a.SK_ID_CURR AS ApplicationID,
    a.DatasetSplit,
    CASE
        WHEN NULLIF(LTRIM(RTRIM(a.CODE_GENDER)), N'') IS NULL
          OR UPPER(LTRIM(RTRIM(a.CODE_GENDER))) = N'XNA' THEN N'Unknown'
        ELSE LTRIM(RTRIM(a.CODE_GENDER))
    END AS GenderCode,
    CASE UPPER(LTRIM(RTRIM(a.FLAG_OWN_CAR))) WHEN N'Y' THEN CONVERT(BIT, 1) WHEN N'N' THEN CONVERT(BIT, 0) END AS OwnCarFlag,
    CASE UPPER(LTRIM(RTRIM(a.FLAG_OWN_REALTY))) WHEN N'Y' THEN CONVERT(BIT, 1) WHEN N'N' THEN CONVERT(BIT, 0) END AS OwnRealtyFlag,
    CONVERT(INT, a.CNT_CHILDREN) AS ChildrenCount,
    CONVERT(DECIMAL(19,2), a.AMT_INCOME_TOTAL) AS IncomeAmount,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.NAME_INCOME_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.NAME_INCOME_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.NAME_INCOME_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.NAME_INCOME_TYPE)) END AS IncomeType,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.NAME_EDUCATION_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.NAME_EDUCATION_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.NAME_EDUCATION_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.NAME_EDUCATION_TYPE)) END AS EducationType,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.NAME_FAMILY_STATUS)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.NAME_FAMILY_STATUS))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.NAME_FAMILY_STATUS))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.NAME_FAMILY_STATUS)) END AS FamilyStatus,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.NAME_HOUSING_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.NAME_HOUSING_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.NAME_HOUSING_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.NAME_HOUSING_TYPE)) END AS HousingType,
    CASE WHEN a.DAYS_BIRTH < 0 THEN CONVERT(SMALLINT, FLOOR(-a.DAYS_BIRTH / 365.25)) END AS AgeYears,
    CASE WHEN a.DAYS_EMPLOYED = 365243 THEN NULL WHEN a.DAYS_EMPLOYED < 0 THEN CONVERT(INT, -a.DAYS_EMPLOYED) END AS EmploymentTenureDays,
    CONVERT(BIT, CASE WHEN a.DAYS_EMPLOYED = 365243 THEN 1 ELSE 0 END) AS EmploymentSentinelFlag,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.OCCUPATION_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.OCCUPATION_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.OCCUPATION_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.OCCUPATION_TYPE)) END AS OccupationType,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.ORGANIZATION_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.ORGANIZATION_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.ORGANIZATION_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.ORGANIZATION_TYPE)) END AS OrganizationType,
    CONVERT(DECIMAL(9,2), a.CNT_FAM_MEMBERS) AS FamilyMemberCount,
    CONVERT(DECIMAL(18,10), a.REGION_POPULATION_RELATIVE) AS RegionPopulationRelative,
    CONVERT(INT, a.REGION_RATING_CLIENT) AS RegionRating,
    CONVERT(INT, a.REGION_RATING_CLIENT_W_CITY) AS RegionCityRating,
    CONVERT(INT, a.OWN_CAR_AGE) AS CarAgeYears,
    CONVERT(BIT, CASE WHEN NULLIF(LTRIM(RTRIM(a.CODE_GENDER)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.CODE_GENDER))) = N'XNA' THEN 1 ELSE 0 END) AS GenderUnknownFlag,
    a.BatchID AS SourceBatchID
FROM stg.Application AS a
WHERE a.SK_ID_CURR IS NOT NULL;
GO

CREATE OR ALTER VIEW etl.vw_CleanLoanApplication
AS
SELECT
    a.SK_ID_CURR AS ApplicationID,
    CONVERT(BIT, a.TARGET) AS TargetFlag,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.NAME_CONTRACT_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.NAME_CONTRACT_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.NAME_CONTRACT_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.NAME_CONTRACT_TYPE)) END AS ContractType,
    CONVERT(DECIMAL(19,2), a.AMT_CREDIT) AS CreditAmount,
    CONVERT(DECIMAL(19,2), a.AMT_ANNUITY) AS AnnuityAmount,
    CONVERT(DECIMAL(19,2), a.AMT_GOODS_PRICE) AS GoodsPriceAmount,
    CASE WHEN NULLIF(LTRIM(RTRIM(a.NAME_TYPE_SUITE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(a.NAME_TYPE_SUITE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(a.NAME_TYPE_SUITE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(a.NAME_TYPE_SUITE)) END AS SuiteType,
    LTRIM(RTRIM(a.WEEKDAY_APPR_PROCESS_START)) AS ApplicationWeekday,
    CONVERT(TINYINT, a.HOUR_APPR_PROCESS_START) AS ApplicationHour,
    CONVERT(DECIMAL(18,10), a.EXT_SOURCE_1) AS ExternalScore1,
    CONVERT(DECIMAL(18,10), a.EXT_SOURCE_2) AS ExternalScore2,
    CONVERT(DECIMAL(18,10), a.EXT_SOURCE_3) AS ExternalScore3,
    CONVERT(BIT, CASE WHEN a.AMT_ANNUITY IS NULL THEN 1 ELSE 0 END) AS MissingAnnuityFlag,
    CONVERT(BIT, CASE WHEN a.AMT_GOODS_PRICE IS NULL THEN 1 ELSE 0 END) AS MissingGoodsPriceFlag,
    a.BatchID AS SourceBatchID
FROM stg.Application AS a
WHERE a.SK_ID_CURR IS NOT NULL;
GO

CREATE OR ALTER VIEW etl.vw_CleanPreviousApplication
AS
SELECT
    p.SK_ID_PREV AS PreviousApplicationID,
    p.SK_ID_CURR AS ApplicationID,
    CASE WHEN NULLIF(LTRIM(RTRIM(p.NAME_CONTRACT_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(p.NAME_CONTRACT_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(p.NAME_CONTRACT_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(p.NAME_CONTRACT_TYPE)) END AS ContractType,
    CASE WHEN NULLIF(LTRIM(RTRIM(p.NAME_CONTRACT_STATUS)), N'') IS NULL OR UPPER(LTRIM(RTRIM(p.NAME_CONTRACT_STATUS))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(p.NAME_CONTRACT_STATUS))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(p.NAME_CONTRACT_STATUS)) END AS ContractStatus,
    CASE WHEN NULLIF(LTRIM(RTRIM(p.NAME_CLIENT_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(p.NAME_CLIENT_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(p.NAME_CLIENT_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(p.NAME_CLIENT_TYPE)) END AS ClientType,
    CASE WHEN NULLIF(LTRIM(RTRIM(p.NAME_PORTFOLIO)), N'') IS NULL OR UPPER(LTRIM(RTRIM(p.NAME_PORTFOLIO))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(p.NAME_PORTFOLIO))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(p.NAME_PORTFOLIO)) END AS PortfolioType,
    CASE WHEN NULLIF(LTRIM(RTRIM(p.NAME_PRODUCT_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(p.NAME_PRODUCT_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(p.NAME_PRODUCT_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(p.NAME_PRODUCT_TYPE)) END AS ProductType,
    CONVERT(DECIMAL(19,2), p.AMT_APPLICATION) AS ApplicationAmount,
    CONVERT(DECIMAL(19,2), p.AMT_CREDIT) AS CreditAmount,
    CONVERT(DECIMAL(19,2), p.AMT_ANNUITY) AS AnnuityAmount,
    CONVERT(DECIMAL(19,2), p.AMT_DOWN_PAYMENT) AS DownPaymentAmount,
    CONVERT(DECIMAL(19,2), p.AMT_GOODS_PRICE) AS GoodsPriceAmount,
    CONVERT(INT, p.DAYS_DECISION) AS DecisionDaysRelative,
    CONVERT(DECIMAL(12,2), p.CNT_PAYMENT) AS PaymentCount,
    CASE WHEN p.DAYS_FIRST_DRAWING = 365243 THEN NULL ELSE CONVERT(INT, p.DAYS_FIRST_DRAWING) END AS FirstDrawingDaysRelative,
    CASE WHEN p.DAYS_FIRST_DUE = 365243 THEN NULL ELSE CONVERT(INT, p.DAYS_FIRST_DUE) END AS FirstDueDaysRelative,
    CASE WHEN p.DAYS_LAST_DUE_1ST_VERSION = 365243 THEN NULL ELSE CONVERT(INT, p.DAYS_LAST_DUE_1ST_VERSION) END AS LastDueFirstVersionDaysRelative,
    CASE WHEN p.DAYS_LAST_DUE = 365243 THEN NULL ELSE CONVERT(INT, p.DAYS_LAST_DUE) END AS LastDueDaysRelative,
    CASE WHEN p.DAYS_TERMINATION = 365243 THEN NULL ELSE CONVERT(INT, p.DAYS_TERMINATION) END AS TerminationDaysRelative,
    CONVERT(BIT, CASE WHEN p.DAYS_FIRST_DRAWING = 365243 OR p.DAYS_FIRST_DUE = 365243 OR p.DAYS_LAST_DUE_1ST_VERSION = 365243 OR p.DAYS_LAST_DUE = 365243 OR p.DAYS_TERMINATION = 365243 THEN 1 ELSE 0 END) AS DateSentinelFlag,
    CONVERT(BIT, CASE WHEN p.CNT_PAYMENT <= 0 THEN 1 ELSE 0 END) AS NonPositivePaymentCountFlag,
    CONVERT(BIT, CASE WHEN p.AMT_APPLICATION < 0 OR p.AMT_CREDIT < 0 OR p.AMT_ANNUITY < 0 OR p.AMT_DOWN_PAYMENT < 0 OR p.AMT_GOODS_PRICE < 0 THEN 1 ELSE 0 END) AS NegativeAmountFlag,
    p.BatchID AS SourceBatchID
FROM stg.PreviousApplication AS p
WHERE p.SK_ID_PREV IS NOT NULL AND p.SK_ID_CURR IS NOT NULL;
GO

CREATE OR ALTER VIEW etl.vw_CleanBureauCredit
AS
SELECT
    b.SK_ID_BUREAU AS BureauCreditID,
    b.SK_ID_CURR AS ApplicationID,
    COALESCE(NULLIF(LTRIM(RTRIM(b.CREDIT_ACTIVE)), N''), N'Unknown') AS CreditStatus,
    COALESCE(NULLIF(LTRIM(RTRIM(b.CREDIT_CURRENCY)), N''), N'Unknown') AS CreditCurrency,
    CASE WHEN NULLIF(LTRIM(RTRIM(b.CREDIT_TYPE)), N'') IS NULL OR UPPER(LTRIM(RTRIM(b.CREDIT_TYPE))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(b.CREDIT_TYPE))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(b.CREDIT_TYPE)) END AS CreditType,
    CONVERT(INT, b.DAYS_CREDIT) AS CreditDaysRelative,
    CONVERT(INT, b.DAYS_CREDIT_ENDDATE) AS CreditEndDaysRelative,
    CONVERT(INT, b.DAYS_ENDDATE_FACT) AS ActualEndDaysRelative,
    CONVERT(INT, b.DAYS_CREDIT_UPDATE) AS UpdateDaysRelative,
    CONVERT(INT, b.CREDIT_DAY_OVERDUE) AS OverdueDays,
    CONVERT(DECIMAL(19,2), b.AMT_CREDIT_SUM) AS CreditAmount,
    CONVERT(DECIMAL(19,2), b.AMT_CREDIT_SUM_DEBT) AS DebtAmount,
    CONVERT(DECIMAL(19,2), b.AMT_CREDIT_SUM_LIMIT) AS CreditLimitAmount,
    CONVERT(DECIMAL(19,2), b.AMT_CREDIT_SUM_OVERDUE) AS OverdueAmount,
    CONVERT(DECIMAL(19,2), b.AMT_CREDIT_MAX_OVERDUE) AS MaxOverdueAmount,
    CONVERT(DECIMAL(19,2), b.AMT_ANNUITY) AS AnnuityAmount,
    CONVERT(INT, b.CNT_CREDIT_PROLONG) AS ProlongationCount,
    CONVERT(BIT, CASE WHEN b.AMT_CREDIT_SUM_DEBT < 0 THEN 1 ELSE 0 END) AS NegativeDebtFlag,
    b.BatchID AS SourceBatchID
FROM stg.BureauCredit AS b
WHERE b.SK_ID_BUREAU IS NOT NULL AND b.SK_ID_CURR IS NOT NULL;
GO

CREATE OR ALTER VIEW etl.vw_CleanBureauMonthlyStatus
AS
SELECT
    bb.SK_ID_BUREAU AS BureauCreditID,
    CONVERT(INT, bb.MONTHS_BALANCE) AS RelativeMonth,
    COALESCE(NULLIF(LTRIM(RTRIM(bb.STATUS)), N''), N'Unknown') AS StatusCode,
    CONVERT(BIT, CASE WHEN b.SK_ID_BUREAU IS NULL THEN 1 ELSE 0 END) AS ParentMissingFlag,
    bb.SourceRowNumber,
    bb.BatchID AS SourceBatchID
FROM stg.BureauBalance AS bb
LEFT JOIN stg.BureauCredit AS b
  ON b.BatchID = bb.BatchID AND b.SK_ID_BUREAU = bb.SK_ID_BUREAU
WHERE bb.SK_ID_BUREAU IS NOT NULL AND bb.MONTHS_BALANCE IS NOT NULL;
GO

CREATE OR ALTER VIEW etl.vw_CleanInstallmentPayment
AS
SELECT
    i.SK_ID_PREV AS PreviousApplicationID,
    i.SK_ID_CURR AS ApplicationID,
    CONVERT(DECIMAL(12,2), i.NUM_INSTALMENT_VERSION) AS InstallmentVersion,
    CONVERT(INT, i.NUM_INSTALMENT_NUMBER) AS InstallmentNumber,
    CONVERT(INT, i.DAYS_INSTALMENT) AS DueDaysRelative,
    CONVERT(INT, i.DAYS_ENTRY_PAYMENT) AS PaymentDaysRelative,
    CONVERT(DECIMAL(19,2), i.AMT_INSTALMENT) AS ScheduledAmount,
    CONVERT(DECIMAL(19,2), i.AMT_PAYMENT) AS PaidAmount,
    CASE WHEN i.DAYS_ENTRY_PAYMENT IS NOT NULL AND i.DAYS_INSTALMENT IS NOT NULL THEN CONVERT(INT, i.DAYS_ENTRY_PAYMENT - i.DAYS_INSTALMENT) END AS PaymentDelayDays,
    CASE WHEN i.DAYS_ENTRY_PAYMENT IS NOT NULL AND i.DAYS_INSTALMENT IS NOT NULL AND i.DAYS_ENTRY_PAYMENT > i.DAYS_INSTALMENT THEN CONVERT(INT, i.DAYS_ENTRY_PAYMENT - i.DAYS_INSTALMENT) ELSE 0 END AS DaysLate,
    CASE WHEN i.AMT_PAYMENT IS NOT NULL AND i.AMT_INSTALMENT IS NOT NULL THEN CONVERT(DECIMAL(19,2), i.AMT_PAYMENT - i.AMT_INSTALMENT) END AS PaymentVarianceAmount,
    CONVERT(BIT, CASE WHEN i.DAYS_ENTRY_PAYMENT IS NOT NULL AND i.AMT_PAYMENT IS NOT NULL THEN 1 ELSE 0 END) AS PaymentRecordedFlag,
    CONVERT(BIT, CASE WHEN p.SK_ID_PREV IS NULL THEN 1 ELSE 0 END) AS ParentMissingFlag,
    i.SourceRowNumber,
    i.BatchID AS SourceBatchID
FROM stg.InstallmentPayment AS i
LEFT JOIN stg.PreviousApplication AS p
  ON p.BatchID = i.BatchID AND p.SK_ID_PREV = i.SK_ID_PREV
WHERE i.SK_ID_PREV IS NOT NULL AND i.SK_ID_CURR IS NOT NULL;
GO

CREATE OR ALTER VIEW etl.vw_CleanPOSCashMonthly
AS
SELECT
    m.SK_ID_PREV AS PreviousApplicationID,
    m.SK_ID_CURR AS ApplicationID,
    CONVERT(INT, m.MONTHS_BALANCE) AS RelativeMonth,
    CONVERT(DECIMAL(12,2), m.CNT_INSTALMENT) AS InstallmentCount,
    CONVERT(DECIMAL(12,2), m.CNT_INSTALMENT_FUTURE) AS FutureInstallmentCount,
    CASE WHEN NULLIF(LTRIM(RTRIM(m.NAME_CONTRACT_STATUS)), N'') IS NULL OR UPPER(LTRIM(RTRIM(m.NAME_CONTRACT_STATUS))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(m.NAME_CONTRACT_STATUS))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(m.NAME_CONTRACT_STATUS)) END AS ContractStatus,
    CONVERT(INT, m.SK_DPD) AS DaysPastDue,
    CONVERT(INT, m.SK_DPD_DEF) AS DaysPastDueTolerance,
    CONVERT(BIT, CASE WHEN p.SK_ID_PREV IS NULL THEN 1 ELSE 0 END) AS ParentMissingFlag,
    m.SourceRowNumber,
    m.BatchID AS SourceBatchID
FROM stg.POSCashBalance AS m
LEFT JOIN stg.PreviousApplication AS p
  ON p.BatchID = m.BatchID AND p.SK_ID_PREV = m.SK_ID_PREV
WHERE m.SK_ID_PREV IS NOT NULL AND m.SK_ID_CURR IS NOT NULL AND m.MONTHS_BALANCE IS NOT NULL;
GO

CREATE OR ALTER VIEW etl.vw_CleanCreditCardMonthly
AS
SELECT
    m.SK_ID_PREV AS PreviousApplicationID,
    m.SK_ID_CURR AS ApplicationID,
    CONVERT(INT, m.MONTHS_BALANCE) AS RelativeMonth,
    CONVERT(DECIMAL(19,2), m.AMT_BALANCE) AS BalanceAmount,
    CONVERT(DECIMAL(19,2), m.AMT_CREDIT_LIMIT_ACTUAL) AS CreditLimitAmount,
    CONVERT(DECIMAL(19,2), m.AMT_DRAWINGS_CURRENT) AS DrawingsAmount,
    CONVERT(DECIMAL(19,2), m.AMT_INST_MIN_REGULARITY) AS MinimumInstallmentAmount,
    CONVERT(DECIMAL(19,2), m.AMT_PAYMENT_CURRENT) AS CurrentPaymentAmount,
    CONVERT(DECIMAL(19,2), m.AMT_PAYMENT_TOTAL_CURRENT) AS TotalPaymentAmount,
    CONVERT(DECIMAL(19,2), m.AMT_RECEIVABLE_PRINCIPAL) AS PrincipalReceivableAmount,
    CONVERT(DECIMAL(19,2), m.AMT_TOTAL_RECEIVABLE) AS TotalReceivableAmount,
    CASE WHEN NULLIF(LTRIM(RTRIM(m.NAME_CONTRACT_STATUS)), N'') IS NULL OR UPPER(LTRIM(RTRIM(m.NAME_CONTRACT_STATUS))) = N'XNA' THEN N'Unknown'
         WHEN UPPER(LTRIM(RTRIM(m.NAME_CONTRACT_STATUS))) = N'XAP' THEN N'Not applicable' ELSE LTRIM(RTRIM(m.NAME_CONTRACT_STATUS)) END AS ContractStatus,
    CONVERT(INT, m.SK_DPD) AS DaysPastDue,
    CONVERT(INT, m.SK_DPD_DEF) AS DaysPastDueTolerance,
    CONVERT(BIT, CASE WHEN m.AMT_CREDIT_LIMIT_ACTUAL < 0 THEN 1 ELSE 0 END) AS NegativeLimitFlag,
    CONVERT(BIT, CASE WHEN p.SK_ID_PREV IS NULL THEN 1 ELSE 0 END) AS ParentMissingFlag,
    m.SourceRowNumber,
    m.BatchID AS SourceBatchID
FROM stg.CreditCardBalance AS m
LEFT JOIN stg.PreviousApplication AS p
  ON p.BatchID = m.BatchID AND p.SK_ID_PREV = m.SK_ID_PREV
WHERE m.SK_ID_PREV IS NOT NULL AND m.SK_ID_CURR IS NOT NULL AND m.MONTHS_BALANCE IS NOT NULL;
GO
